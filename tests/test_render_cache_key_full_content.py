"""The per-message render cache must never serve one message's HTML for another.

`_renderCacheKey()` keyed long bodies (> 500 chars) on length + first 20 + last 20 characters. Two messages with the
same length and the same edges but a different middle (templated status reports, a regenerated answer, an edited code
block) got the same key, and the second one displayed the first one's rendered body. Found while seeding a
240-message session for the #5106 screenshots: message 239 showed message 219's text on master.
"""
import json
import pathlib
import shutil
import subprocess

import pytest

REPO = pathlib.Path(__file__).parent.parent
UI_JS = REPO / "static" / "ui.js"
NODE = shutil.which("node")
needs_node = pytest.mark.skipif(NODE is None, reason="node required")

_DRIVER = r"""
const fs = require('fs');
const src = fs.readFileSync(process.argv[1], 'utf8');
function extract(name) {
  const start = src.indexOf('function ' + name + '(');
  if (start < 0) throw new Error(name + ' not found');
  let i = src.indexOf('{', start), depth = 1; i++;
  while (depth > 0) { if (src[i] === '{') depth++; else if (src[i] === '}') depth--; i++; }
  return src.slice(start, i);
}
global.window = { _renderUserMarkdown: false };
let renders = 0;
global.renderMd = (t) => { renders++; return '<p>' + t + '</p>'; };
global._stripXmlToolCallsDisplay = (s) => s;
global._renderUserFencedBlocks = (t) => { renders++; return '<pre>' + t + '</pre>'; };
global._renderCache = new Map();
global._renderCacheMax = 300;
for (const name of ['_renderCacheTextHash', '_renderCacheKey', '_getCachedRender']) {
  if (src.indexOf('function ' + name + '(') >= 0) eval.call(global, extract(name));
}
const sc = JSON.parse(process.argv[2]);
const out = sc.texts.map((t) => _getCachedRender(t, sc.isUser));
process.stdout.write(JSON.stringify({ out, renders }));
"""


def _render_all(texts, is_user=False):
    r = subprocess.run([NODE, "-e", _DRIVER, str(UI_JS), json.dumps({"texts": texts, "isUser": is_user})],
                       capture_output=True, text=True, timeout=30)
    assert r.returncode == 0, r.stderr
    return json.loads(r.stdout)


def _same_edges_pair(length=900):
    head = "## Daily status report\n"
    tail = "\n\n-- generated by cron"
    middle_len = length - len(head) - len(tail)
    a = head + ("alpha " * 400)[:middle_len] + tail
    b = head + ("bravo " * 400)[:middle_len] + tail
    assert len(a) == len(b) == length and a[:20] == b[:20] and a[-20:] == b[-20:] and a != b
    return a, b


@needs_node
@pytest.mark.parametrize("is_user", [False, True])
def test_equal_length_bodies_with_equal_edges_render_their_own_content(is_user):
    a, b = _same_edges_pair()
    res = _render_all([a, b], is_user)
    assert "alpha" in res["out"][0] and "bravo" not in res["out"][0]
    assert "bravo" in res["out"][1] and "alpha" not in res["out"][1], "second message showed the first one's body"
    assert res["renders"] == 2


@needs_node
def test_one_character_change_in_the_middle_changes_the_key():
    a, _ = _same_edges_pair()
    mid = len(a) // 2
    b = a[:mid] + ("X" if a[mid] != "X" else "Y") + a[mid + 1:]
    res = _render_all([a, b])
    assert res["out"][0] != res["out"][1]
    assert res["renders"] == 2


@needs_node
def test_identical_long_bodies_still_hit_the_cache():
    a, _ = _same_edges_pair()
    res = _render_all([a, a, a])
    assert res["renders"] == 1
    assert res["out"][0] == res["out"][1] == res["out"][2]


@needs_node
def test_short_bodies_keep_the_full_text_key():
    res = _render_all(["hello", "hello", "world"])
    assert res["renders"] == 2
