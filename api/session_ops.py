"""Session-mutation operations for slash commands (/retry, /undo) and
read-only aggregators (/status, /usage). Operates on the webui's own
JSON Session store (api/models.py). Durable history mutations (checkpoint
restore, per-message delete) additionally go through hermes-agent's SessionDB
transaction authority — SessionDB.rewind_to_message / replace_messages — as
of the PR #7075 review rework (see _commit_rewind_via_authority and
_commit_durable_delete); nothing here hand-rolls SQLite writes.

Behavior parity reference: gateway/run.py:_handle_*_command in
the hermes-agent repo.
"""
from __future__ import annotations
import json
import logging
import os
import uuid
from bisect import bisect_left
from typing import Any

from api.config import LOCK, _get_session_agent_lock
from api.models import get_session, SESSIONS

logger = logging.getLogger(__name__)

AUTO_TITLE_LABELS = {'untitled', 'new chat'}


class CheckpointBusyError(ValueError):
    """A live turn / compression currently owns the transcript.

    Raised by the checkpoint-restore / per-message-delete durable paths when
    the Agent's in-transaction guard refuses because a non-stale turn lease or
    a compression lock is held (or the session is closed by compression).
    Nothing was written; the caller can retry once the turn finishes. The
    routes map this to 409 so the client can tell "retry later" apart from
    "bad target" (400).
    """


class CheckpointStaleError(ValueError):
    """The transcript moved under the caller's snapshot.

    Raised when the Agent's in-transaction CAS rejects the durable write
    (active-set identity / target payload changed), or when display rows
    cannot be attributed to the durable transcript because the view is stale.
    Nothing was written; the client should reload the session and retry.
    """


def _row_signature(row: Any) -> tuple[str, ...] | None:
    """Stable identity tuple for a message row.

    Promoted to module scope so it can be reused by both
    ``truncate_context_for_display_keep`` (display↔context alignment) and
    ``delete_message_at_signature`` (per-message splice). The signature is
    the same tuple the inner matcher used to compute, so existing alignment
    behavior is unchanged. A non-dict row returns ``None`` (caller treats it
    as unmatchable).
    """
    if not isinstance(row, dict):
        return None
    tool_calls = row.get('tool_calls')
    tool_calls_sig = json.dumps(tool_calls, sort_keys=True, default=str) if tool_calls else ''
    return (
        str(row.get('role') or ''),
        str(row.get('content') or ''),
        str(row.get('tool_call_id') or ''),
        str(row.get('tool_use_id') or ''),
        str(row.get('tool_name') or row.get('name') or ''),
        tool_calls_sig,
    )


def _live_active_stream_id(session) -> str | None:
    """Return session.active_stream_id ONLY if that stream is live in THIS
    process; else None.

    After a restart/crash the persisted active_stream_id survives in the
    session JSON but the in-memory STREAMS / ACTIVE_RUNS that actually drive a
    live turn were wiped. Exposing that dead id (e.g. via /api/session/status to
    the hidden-tab poller) would make a client attach its renderer to a stream
    that never emits — a permanent fake "thinking" state. Liveness test mirrors
    routes._clear_stale_stream_state: live iff present in STREAMS (open SSE
    channel) or ACTIVE_RUNS (worker bookkeeping).
    """
    stream_id = getattr(session, 'active_stream_id', None)
    if not stream_id:
        return None
    try:
        from api import config as _cfg
        with _cfg.STREAMS_LOCK:
            if stream_id in _cfg.STREAMS:
                return stream_id
        with _cfg.ACTIVE_RUNS_LOCK:
            if stream_id in (_cfg.ACTIVE_RUNS or {}):
                return stream_id
    except Exception:
        # On any introspection failure, fail SAFE (report no live stream) rather
        # than surfacing a possibly-stale id.
        return None
    return None


def session_has_manual_title(session) -> bool:
    """Return whether adaptive title refresh should leave this title alone."""
    return getattr(session, 'manual_title', False) is True


def apply_session_title_rename(session, raw_title) -> str:
    """Apply user-driven rename semantics to a Session object.

    Non-empty custom titles are protected from adaptive refresh. Clearing the
    title, or resetting it to an automatic label, removes that protection so the
    normal auto-title path can run again.
    """
    title = str(raw_title or '').strip()[:80]
    if not title:
        title = 'Untitled'
    manual_title = title.strip().casefold() not in AUTO_TITLE_LABELS
    session.title = title
    session.manual_title = manual_title
    session.llm_title_generated = False
    return title


def mark_session_title_generated(session) -> None:
    """Mark a session title as generated by the title model."""
    session.llm_title_generated = True
    session.manual_title = False


def _truncate_at_last_user(messages):
    history = messages or []
    last_user_idx = None
    for i in range(len(history) - 1, -1, -1):
        if isinstance(history[i], dict) and history[i].get('role') == 'user':
            last_user_idx = i
            break
    if last_user_idx is None:
        return None
    return history[:last_user_idx]


def _truncation_watermark_for(messages):
    history = list(messages or [])
    if not history:
        return 0.0
    try:
        return float(history[-1].get('timestamp') or 0)
    except (AttributeError, TypeError, ValueError):
        return 0.0


def _stamp_intentional_shrink_generation(session, old_message_count: int, new_message_count: int) -> bool:
    """Stamp a new generation only when the visible message list shrinks."""
    if new_message_count >= old_message_count:
        return False
    session.intentional_shrink_generation = uuid.uuid4().hex
    return True


def truncate_context_for_display_keep(
    context_messages: list | None,
    full_messages: list | None,
    keep: int,
) -> list:
    """Align model context with display prefix ``full_messages[:keep]``."""
    if keep <= 0:
        return []
    ctx = context_messages if isinstance(context_messages, list) else []
    msgs = full_messages if isinstance(full_messages, list) else []
    if not ctx:
        return []
    if len(msgs) == 0:
        return []
    # Only the perfectly-parallel case (display and context row-for-row) can be
    # sliced at the raw display index. When the two arrays differ in length —
    # in EITHER direction — they have diverged and need alignment:
    #   * context LONGER than display  → an injected summary/system prefix, etc.
    #   * context SHORTER than display → large-session context trimming dropped
    #     turns from the model context that the display still shows.
    # The shorter-context case is the one that broke forked large sessions: the
    # old ``len(ctx) <= len(msgs)`` guard short-circuited to ``ctx[:keep]``,
    # slicing the shorter context at the display index (landing mid-turn, e.g.
    # on an assistant tool_call whose result was past the cut). Fall through to
    # the signature matcher for both divergent cases so the cut lands on a real
    # turn boundary. Any residual dangling tool_use in the persisted context is
    # made wire-safe on the send path (streaming: ``_sanitize_messages_for_api``
    # strips unanswered tool_calls; gateway: it forwards no tool_calls/tool rows
    # at all), so we do not re-do that trimming here.
    if len(ctx) == len(msgs):
        return ctx[:keep]

    # Materialize signatures once.  The matcher deliberately keeps the original
    # rows in ``ctx``; these records are only an alignment index. A signature
    # failure is deferred because the old matcher may return before reaching it.
    context_records = []
    deferred_signature_positions: list[int] = []
    for idx, row in enumerate(ctx):
        try:
            row_signature = _row_signature(row)
        except Exception:
            row_signature = None
            deferred_signature_positions.append(idx)
        context_records.append((row, row_signature))
    message_signatures = [_row_signature(message) for message in msgs]
    id_positions: dict[Any, list[int]] = {}
    signature_positions: dict[tuple[str, ...], list[int]] = {}
    signature_no_id_positions: dict[tuple[str, ...], list[int]] = {}
    signature_no_timestamp_positions: dict[tuple[str, ...], list[int]] = {}
    signature_no_id_no_timestamp_positions: dict[tuple[str, ...], list[int]] = {}
    signature_timestamp_positions: dict[
        tuple[tuple[str, ...], Any], list[int]
    ] = {}
    signature_timestamp_no_id_positions: dict[
        tuple[tuple[str, ...], Any], list[int]
    ] = {}
    unsafe_id_positions: list[int] = []
    unsafe_timestamp_positions: dict[tuple[str, ...], list[int]] = {}
    unsafe_timestamp_no_id_positions: dict[tuple[str, ...], list[int]] = {}

    def _safe_raw_value(value: Any) -> bool:
        # Keep dict lookup semantics aligned with the old explicit ``==`` scan:
        # only ordinary built-in metadata values may use the raw-value indexes.
        # In particular, custom objects and non-reflexive NaN values can make a
        # dict find a key that the old equality check rejected.
        if value is None:
            return True
        if type(value) not in (str, int, float):
            return False
        try:
            hash(value)
            return value == value
        except Exception:
            return False

    for idx, (context_row, context_sig) in enumerate(context_records):
        if context_sig is not None:
            signature_positions.setdefault(context_sig, []).append(idx)
        if not isinstance(context_row, dict):
            continue
        context_id = context_row.get('id')
        context_ts = context_row.get('timestamp')
        if context_sig is not None:
            if context_id is None:
                signature_no_id_positions.setdefault(context_sig, []).append(idx)
            if context_ts is None:
                signature_no_timestamp_positions.setdefault(context_sig, []).append(idx)
            if context_id is None and context_ts is None:
                signature_no_id_no_timestamp_positions.setdefault(
                    context_sig, []
                ).append(idx)
        if context_id is not None and _safe_raw_value(context_id):
            id_positions.setdefault(context_id, []).append(idx)
        elif context_id is not None:
            unsafe_id_positions.append(idx)
        if (
            context_sig is not None
            and context_ts is not None
            and _safe_raw_value(context_ts)
        ):
            timestamp_key = (context_sig, context_ts)
            signature_timestamp_positions.setdefault(timestamp_key, []).append(idx)
            if context_id is None:
                signature_timestamp_no_id_positions.setdefault(
                    timestamp_key, []
                ).append(idx)
        elif context_sig is not None and context_ts is not None:
            unsafe_timestamp_positions.setdefault(context_sig, []).append(idx)
            if context_id is None:
                unsafe_timestamp_no_id_positions.setdefault(
                    context_sig, []
                ).append(idx)

    def _first_at_or_after(positions: list[int] | None, start_idx: int) -> int | None:
        if not positions:
            return None
        offset = bisect_left(positions, start_idx)
        return positions[offset] if offset < len(positions) else None

    def _lazy_first_match_from(
        message: Any,
        start_idx: int,
    ) -> tuple[int | None, int | None]:
        """Match exactly as the original ordered scan did."""
        msg_sig = _row_signature(message)
        if msg_sig is None:
            return None, None
        weak_matches: list[int] = []
        for idx in range(start_idx, len(ctx)):
            context_row = ctx[idx]
            context_sig = _row_signature(context_row)
            if context_sig is None or not isinstance(context_row, dict):
                continue
            context_id = context_row.get('id')
            msg_id = message.get('id')
            if context_id is not None and msg_id is not None:
                if context_id == msg_id:
                    return idx, None
                continue
            if context_sig != msg_sig:
                continue
            context_ts = context_row.get('timestamp')
            msg_ts = message.get('timestamp')
            if context_ts is not None and msg_ts is not None:
                if context_ts == msg_ts:
                    return idx, None
                continue
            weak_matches.append(idx)
            if len(weak_matches) > 1:
                return None, weak_matches[0]
        return (weak_matches[0], None) if len(weak_matches) == 1 else (None, None)

    def _first_match_from(
        message_idx: int,
        message: Any,
        start_idx: int,
    ) -> tuple[int | None, int | None]:
        msg_sig = message_signatures[message_idx]
        if msg_sig is None:
            return None, None
        msg_id = message.get('id')
        msg_ts = message.get('timestamp')
        deferred_reachable = _first_at_or_after(
            deferred_signature_positions, start_idx
        ) is not None
        unsafe_id_reachable = (
            msg_id is not None
            and _first_at_or_after(unsafe_id_positions, start_idx) is not None
        )
        unsafe_timestamp_candidates = (
            unsafe_timestamp_no_id_positions.get(msg_sig, [])
            if msg_id is not None
            else unsafe_timestamp_positions.get(msg_sig, [])
        )
        unsafe_timestamp_reachable = (
            msg_ts is not None
            and _first_at_or_after(unsafe_timestamp_candidates, start_idx) is not None
        )
        if not _safe_raw_value(msg_id) or not _safe_raw_value(msg_ts):
            return _lazy_first_match_from(message, start_idx)
        if deferred_reachable or unsafe_id_reachable or unsafe_timestamp_reachable:
            return _lazy_first_match_from(message, start_idx)

        exact_positions: list[int] = []
        if msg_id is not None:
            id_idx = _first_at_or_after(id_positions.get(msg_id), start_idx)
            if id_idx is not None:
                exact_positions.append(id_idx)
        if msg_ts is not None:
            timestamp_key = (msg_sig, msg_ts)
            if msg_id is not None:
                timestamp_positions = signature_timestamp_no_id_positions.get(
                    timestamp_key, []
                )
            else:
                timestamp_positions = signature_timestamp_positions.get(
                    timestamp_key, []
                )
            timestamp_idx = _first_at_or_after(timestamp_positions, start_idx)
            if timestamp_idx is not None:
                exact_positions.append(timestamp_idx)
        exact_idx = min(exact_positions, default=None)

        if msg_id is not None and msg_ts is not None:
            weak_candidates = signature_no_id_no_timestamp_positions.get(msg_sig)
        elif msg_id is not None:
            weak_candidates = signature_no_id_positions.get(msg_sig)
        elif msg_ts is not None:
            weak_candidates = signature_no_timestamp_positions.get(msg_sig)
        else:
            weak_candidates = signature_positions.get(msg_sig)
        weak_start = bisect_left(weak_candidates, start_idx) if weak_candidates else 0
        weak_positions = weak_candidates[weak_start:weak_start + 2] if weak_candidates else []
        second_weak_idx = weak_positions[1] if len(weak_positions) > 1 else None
        if second_weak_idx is not None and (
            exact_idx is None or second_weak_idx < exact_idx
        ):
            return None, weak_positions[0]
        if exact_idx is not None:
            return exact_idx, None
        return (weak_positions[0], None) if len(weak_positions) == 1 else (None, None)

    matches = [None] * len(msgs)
    ambiguous_matches = [None] * len(msgs)
    next_ctx_idx = 0
    for msg_idx, message in enumerate(msgs):
        match_idx, ambiguous_idx = _first_match_from(msg_idx, message, next_ctx_idx)
        matches[msg_idx] = match_idx
        ambiguous_matches[msg_idx] = ambiguous_idx
        if match_idx is not None:
            next_ctx_idx = match_idx + 1

    # Cut at the first unkept display turn, or fallback to the last kept turn
    # if the boundary is not directly alignable.
    if keep < len(msgs):
        last_kept = None
        if keep > 0:
            last_kept = matches[keep - 1]
        first_unkept = matches[keep]
        if first_unkept is not None:
            if (
                last_kept is not None
                and isinstance(msgs[keep - 1], dict)
                and msgs[keep - 1].get('role') == 'user'
            ):
                return ctx[:last_kept + 1]
            return ctx[:first_unkept]
        if last_kept is not None:
            ambiguous_first_unkept = ambiguous_matches[keep]
            if (
                ambiguous_first_unkept is not None
                and isinstance(msgs[keep - 1], dict)
                and msgs[keep - 1].get('role') != 'user'
            ):
                return ctx[:ambiguous_first_unkept]
            return ctx[:last_kept + 1]

        # Both boundary rows were ambiguous/unmatched (common in large sessions
        # where context rows have lost their id/timestamp so the matcher can't
        # disambiguate structurally-identical rows). Only for the shorter-context
        # case: cut just past the LAST display row in the kept prefix that
        # resolved to a context index — preferring an exact match but accepting
        # an ambiguous (weak) one, mirroring how the sibling branches above fold
        # ``ambiguous_matches`` into the boundary. Accepting the weak match keeps
        # the forked boundary turn's own context (often exactly that ambiguous
        # row) instead of dropping back to an earlier exact match. It still errs
        # toward UNDER-keeping rather than slicing at the raw display index,
        # which would over-keep and mis-attribute later context rows to the kept
        # display turns. The context-longer case (injected summary prefix) is
        # left to the #5096 fallback below, which preserves that prefix.
        if len(ctx) < len(msgs):
            for i in range(keep - 1, -1, -1):
                resolved = matches[i] if matches[i] is not None else ambiguous_matches[i]
                if resolved is not None:
                    return ctx[:resolved + 1]

    # Final fallback preserves #5096 behavior when alignment is unreliable
    # (no display row resolved to a context index, or keep >= len(msgs)).
    prefix_len = max(0, len(ctx) - len(msgs))
    prefix = ctx[:prefix_len]
    suffix = ctx[prefix_len:]
    return prefix + suffix[:keep]


def truncate_session_at_keep(session, keep: int) -> tuple[int, int]:
    """Truncate display + context; set watermark/boundary. Returns old counts."""
    full_messages = list(session.messages or [])
    old_msg_count = len(full_messages)
    old_ctx_count = len(getattr(session, 'context_messages', None) or [])
    session.messages = full_messages[:keep]
    _stamp_intentional_shrink_generation(session, old_msg_count, len(session.messages))
    if isinstance(getattr(session, 'context_messages', None), list):
        session.context_messages = truncate_context_for_display_keep(
            session.context_messages,
            full_messages,
            keep,
        )
    session.truncation_watermark = _truncation_watermark_for(session.messages)
    session.truncation_boundary = session.truncation_watermark
    return old_msg_count, old_ctx_count


def _resolve_ctx_indices_for_messages(
    ctx: list,
    messages: list,
    target_message_ids: set,
) -> list[int]:
    """Return context_indices that should be dropped for the given display message_ids.

    Walks the display list in order and matches each row to its context counterpart
    using the same first-match semantics as truncate_context_for_display_keep:
    id match first, then id+timestamp, then signature (+ optional timestamp).
    The cursor (next_ctx_idx) advances on EVERY matched display row, not just
    on target rows -- otherwise an id-less context row with a duplicate signature
    that precedes the target's true counterpart would be matched first, the
    deleted content would remain in the model history, and an unrelated context
    row would be removed. See PR #7075 review (Greptile comment 3791689081,
    P1) for the failure mode this ordering fixes.

    Returns indices in ascending order. A display row that cannot be resolved
    to a context index is silently skipped (large-session context trimming may
    have already dropped its counterpart). Caller removes indices in reverse
    order to avoid resequencing.
    """
    if not ctx or not messages or not target_message_ids:
        return []

    # First pass: build display_idx -> ctx_idx map by walking both lists in
    # order. The cursor advances on every match so the O(n) pair remains
    # order-preserving (the same guarantee truncate_context_for_display_keep
    # relies on for its large-session alignment).
    matches: list[int | None] = [None] * len(messages)
    next_ctx_idx = 0
    for msg_idx, msg in enumerate(messages):
        if not isinstance(msg, dict):
            continue
        msg_id = msg.get('id')
        msg_sig = _row_signature(msg)
        if msg_sig is None:
            continue
        for ctx_idx in range(next_ctx_idx, len(ctx)):
            ctx_row = ctx[ctx_idx]
            ctx_sig = _row_signature(ctx_row)
            if ctx_sig is None or not isinstance(ctx_row, dict):
                continue
            ctx_id = ctx_row.get('id')
            # Strongest match: row id matches (skips timestamp check entirely).
            if ctx_id is not None and msg_id is not None and ctx_id == msg_id:
                matches[msg_idx] = ctx_idx
                next_ctx_idx = ctx_idx + 1
                break
            # Weak match: signature must match, then timestamp must match
            # too when both are present (mirrors truncate_context_for_display_keep).
            if ctx_sig != msg_sig:
                continue
            ctx_ts = ctx_row.get('timestamp')
            msg_ts = msg.get('timestamp')
            if ctx_ts is not None and msg_ts is not None and ctx_ts != msg_ts:
                continue
            matches[msg_idx] = ctx_idx
            next_ctx_idx = ctx_idx + 1
            break

    # Second pass: collect ctx indices for target rows that resolved.
    ctx_indices: list[int] = []
    for msg_idx, msg in enumerate(messages):
        if not isinstance(msg, dict):
            continue
        if msg.get('id') not in target_message_ids:
            continue
        ctx_idx = matches[msg_idx]
        if ctx_idx is not None:
            ctx_indices.append(ctx_idx)
    return ctx_indices


def delete_message_at_signature(
    session,
    message_id: str,
    scope: str = "pair",
) -> dict[str, Any]:
    """Remove a single message (or its whole turn-pair) from display + context.

    This is the per-message splice primitive that backs
    ``POST /api/session/message/delete``. Unlike truncate_session_at_keep
    (which keeps a prefix), this targets an arbitrary middle row by identity
    while preserving the rest of the conversation.

    The mutation is a splice, not a slice: ``s.messages`` keeps every row whose
    id is not in the dropped set, and ``s.context_messages`` is aligned by
    signature match so the next LLM turn does not see a stale summary that
    referenced the deleted content.

    Args:
        session: the live ``Session`` instance to mutate (caller holds LOCK).
        message_id: the ``id`` field of the row in ``s.messages`` to delete.
        scope: ``"single"`` drops only the targeted row;
               ``"pair"`` (default) also drops the adjacent user/assistant
               sibling on the other side of the turn. The pair collapse
               prevents the "dangling user turn" pathology that some providers
               reject on the next resend (called out by maintainer in #7001).

    Returns:
        Dict with removed display ids, removed context index count, and the
        resulting counts so the handler can log + build the response.

    Raises:
        ValueError: ``message_id`` not found in ``s.messages`` or unknown scope.
    """
    history = list(session.messages or [])
    drop_ids, target_idx = _delete_display_drop_plan(session, message_id, scope)

    # Splice display messages.
    old_msg_count = len(history)
    new_messages = [m for m in history if not (isinstance(m, dict) and m.get('id') in drop_ids)]
    session.messages = new_messages

    # Splice context_messages by signature match. Large-session context trimming
    # may have already dropped the corresponding context row — in that case we
    # no-op (it is already absent from the model context).
    ctx_list = getattr(session, 'context_messages', None)
    removed_ctx_count = 0
    if isinstance(ctx_list, list) and ctx_list:
        ctx_indices = _resolve_ctx_indices_for_messages(ctx_list, history, drop_ids)
        for ctx_idx in reversed(ctx_indices):
            del ctx_list[ctx_idx]
        removed_ctx_count = len(ctx_indices)
        session.context_messages = ctx_list

    # Stamp the shrink so checkpoint + recovery paths can distinguish a
    # legitimate prefix from a deleted suffix (mirrors truncate_session_at_keep).
    _stamp_intentional_shrink_generation(session, old_msg_count, len(session.messages))
    session.truncation_watermark = _truncation_watermark_for(session.messages)
    session.truncation_boundary = session.truncation_watermark

    return {
        'removed_message_ids': sorted(drop_ids),
        'removed_context_count': removed_ctx_count,
        'old_message_count': old_msg_count,
        'new_message_count': len(session.messages),
    }


def delete_message(session_id: str, message_id: str, scope: str = "pair") -> dict[str, Any]:
    """Drop a single message (or its pair) from display + context + the DURABLE transcript.

    Contributor rework for PR #7075 review item #4: the delete is no longer
    sidecar-only. When the session has a durable transcript, the durable rows
    the display delete maps to are removed FIRST through the Agent's
    transaction authority (``SessionDB.replace_messages(archive_dropped=True,
    reject_active_turn_lease=True)`` — soft-archive mode with the in-txn
    live-turn guard); the sidecar is then spliced and published from the
    committed result. A publication failure after the durable commit is
    fail-closed: the session is flagged for resync and the correction is
    recorded in a crash-safe marker (``api/durable_sync``) that every later
    load re-applies — stale sidecar data can never resurrect the removed
    rows. Sessions without a durable transcript keep the historic
    sidecar-only splice (there is nothing durable to update).

    Public entry point. Acquires the session agent lock and serializes the
    read-modify-write of ``s.messages`` + ``s.context_messages`` against the
    checkpoint thread, cancel_stream, and concurrent truncates. Mirror of
    retry_last / undo_last at api/session_ops.py:427 / :488.

    Raises:
        KeyError: session not found.
        ValueError: message_id not found OR unknown scope.
        CheckpointBusyError: a live turn / compression owns the transcript.
        CheckpointStaleError: the target cannot be attributed to the durable
            transcript (reload and retry).
        RuntimeError: durable write or sidecar publication failed (fail-closed;
            the durable store may already carry the commit).
    """
    with _get_session_agent_lock(session_id):
        s = get_session(session_id)  # acquires LOCK transiently
        with LOCK:
            # Stale-object guard — see retry_last for the rationale.
            s = SESSIONS.get(session_id, s)
            all_rows = list(s.messages or [])
            drop_ids, target_idx = _delete_display_drop_plan(s, message_id, scope)
            first_drop_idx = min(
                (
                    i for i, m in enumerate(all_rows)
                    if isinstance(m, dict) and m.get('id') in drop_ids
                ),
                default=None,
            )
        # --- DURABLE FIRST (Agent transaction authority) ---------------------
        # Only when the session actually has durable rows; a pre-persistence
        # session keeps the historic sidecar-only behavior. Any refusal here
        # aborts BEFORE the sidecar is touched — no split state.
        durable_synced = False
        durable_drop: list[int] = []
        if _durable_rows_exist(s):
            plan = _plan_durable_delete(s, session_id, message_id, scope)
            drop_row_ids = [int(x) for x in (plan.get("drop_row_ids") or [])]
            if drop_row_ids:
                _commit_durable_delete(s, session_id, drop_row_ids)
                durable_drop = drop_row_ids
                durable_synced = True
        # --- SIDECAR SPLICE from the committed durable state -----------------
        with LOCK:
            s = SESSIONS.get(session_id, s)  # re-bind after the durable write
            result = delete_message_at_signature(s, message_id, scope)
            if first_drop_idx is not None:
                # replace_messages re-inserts the divergent suffix (from the
                # hole onward) with NEW ids: the old stamps there would point
                # at archived rows — clear them so the next load re-derives
                # the fresh identities from the durable transcript.
                _strip_row_stamps((s.messages or [])[first_drop_idx:])
            if durable_synced:
                # Precise pass: whatever replace_messages re-inserted or
                # archived, no display row may keep a stamp that is no longer
                # an active durable row (loads and restore both fail closed
                # on stale stamps — clear them proactively).
                committed = _durable_active_id_set(session_id)
                if committed is not None:
                    for row in (s.messages or []):
                        stamp = _display_stamp_int(row)
                        if stamp is not None and stamp not in committed:
                            _strip_row_stamps([row])
        marker_fields = {
            "drop_display_ids": result["removed_message_ids"],
            "archived_row_ids": [int(x) for x in durable_drop],
            "profile": getattr(s, "profile", None),
        }
        _publish_session_sidecar(
            s, session_id, marker_kind="delete", marker_fields=marker_fields
        )
    result["durable_synced"] = durable_synced
    result["durable_removed_row_ids"] = [int(x) for x in durable_drop]
    return result


def retry_last(session_id: str) -> dict[str, Any]:
    """Truncate the session to before the last user message, return its text.

    Mirrors gateway/run.py:_handle_retry_command. Caller (webui frontend)
    is expected to put the returned text back in the composer and call
    send() to resume the conversation -- the agent's gateway calls its own
    _handle_message; the webui has no equivalent in-process pipeline.

    Raises:
        KeyError: session not found
        ValueError: no user message in transcript
    """
    # Acquire the per-session agent lock as the outermost lock so that the
    # read-modify-write of s.messages is serialised with the periodic
    # checkpoint thread, cancel_stream, and all other session writers.
    # Lock ordering: _agent_lock → LOCK → _write_session_index (LOCK).
    with _get_session_agent_lock(session_id):
        # get_session() and Session.save() both acquire the module-level LOCK
        # internally (the latter via _write_session_index()), and LOCK is a
        # non-reentrant threading.Lock — so they MUST be called outside our
        # own `with LOCK:` block to avoid self-deadlocking.
        #
        # The race we close is the read-modify-write of s.messages: two
        # concurrent /api/session/retry calls could otherwise both compute the
        # same last_user_idx from the same history and double-truncate. We
        # serialize just the in-memory mutation; persistence happens inside
        # the per-session lock so the checkpoint thread cannot race us.
        #
        # Stale-object guard: on a cache miss, two concurrent get_session()
        # calls can each load and cache a *different* Session instance for the
        # same session_id (the second store clobbers the first). Re-bind to
        # the canonical cached instance inside the lock so the mutation lands
        # on the object the next reader will see, not a stale parallel copy.
        s = get_session(session_id)  # raises KeyError if missing
        with LOCK:
            s = SESSIONS.get(session_id, s)
            history = s.messages or []
            last_user_idx = None
            for i in range(len(history) - 1, -1, -1):
                if history[i].get('role') == 'user':
                    last_user_idx = i
                    break
            if last_user_idx is None:
                raise ValueError('No previous message to retry.')

            last_user_text = _extract_text(history[last_user_idx].get('content', ''))
            removed_count = len(history) - last_user_idx
            s.messages = history[:last_user_idx]
            _stamp_intentional_shrink_generation(s, len(history), len(s.messages))
            s.truncation_watermark = _truncation_watermark_for(s.messages)
            # Persist the original truncate cutoff so empty-sidecar recovery
            # can distinguish legitimate prefix from deleted suffix.
            s.truncation_boundary = s.truncation_watermark
            if isinstance(getattr(s, 'context_messages', None), list) and s.context_messages:
                truncated_context = _truncate_at_last_user(s.context_messages)
                if truncated_context is not None:
                    s.context_messages = truncated_context
        s.save()
    return {'last_user_text': last_user_text, 'removed_count': removed_count}


def _read_active_state_db_rows(session_id: str) -> list[dict] | None:
    """Read ACTIVE state.db rows (oldest first) with durable ids always exposed.

    ``get_state_db_session_messages`` intentionally hides the durable row id
    unless the row carries a replay sidecar (``api_content``), so it cannot
    serve as the restore path's id authority for plain rows — anchor checks
    and suffix archiving silently no-op'd on them. This reader selects ``id``
    unconditionally. Returns ``None`` when state.db is unavailable; ``[]``
    when the session has no active rows.
    """
    try:
        import sqlite3
        from api.models import _active_state_db_path
    except Exception:
        return None
    try:
        db_path = _active_state_db_path()
    except Exception:
        return None
    if not db_path or not os.path.exists(str(db_path)):
        return None
    try:
        conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True, timeout=10.0)
    except Exception:
        return None
    try:
        conn.row_factory = sqlite3.Row
        cur = conn.cursor()
        cur.execute("PRAGMA table_info(messages)")
        columns = {str(row["name"]) for row in cur.fetchall()}
        if not {"id", "role", "content"} <= columns:
            return None
        parts = ["id", "role", "content"]
        parts.append("api_content" if "api_content" in columns else "NULL AS api_content")
        where = "session_id=?"
        if "active" in columns:
            where += " AND (active IS NULL OR active != 0)"
        cur.execute(
            f"SELECT {', '.join(parts)} FROM messages WHERE {where} ORDER BY id",
            (str(session_id),),
        )
        out: list[dict] = []
        for row in cur.fetchall():
            try:
                rid = int(row["id"])
            except (TypeError, ValueError):
                continue
            out.append({
                "id": rid,
                "role": str(row["role"] or "").lower(),
                "content": row["content"],
                "api_content": row["api_content"],
            })
        return out
    except Exception:
        return None
    finally:
        try:
            conn.close()
        except Exception:
            pass


def _state_db_active_row_by_id(session_id: str, row_id: int):
    """Return the ACTIVE state.db row dict whose durable id equals ``row_id``.

    Backed by :func:`_read_active_state_db_rows` — ids are always exposed on
    plain rows (the generic reader hides them without an ``api_content``
    replay sidecar, which previously made this validation fail closed on
    ordinary rows). Returns ``None`` when the id is absent, inactive, or
    unreadable. This is the single durable authority used by the restore
    path — it never trusts the WebUI sidecar ordinal, because tool /
    reasoning / compaction rows make the two lists diverge (see tui_gateway
    _resolve_truncate_row_id for the gateway's equivalent guard).
    """
    rows = _read_active_state_db_rows(session_id)
    if rows is None:
        return None
    for r in rows:
        if r["id"] == row_id:
            return r
    return None


def _session_state_db_path(session):
    """Resolve the Agent state.db path for *session* (profile-aware).

    Mirrors ``api/checkpoint_map.load_active_user_rows``' resolution so the
    resolver and the write path always address the SAME database (a profile
    mismatch here would read one transcript and archive another).
    """
    try:
        from api.models import _agent_state_db_path
        return _agent_state_db_path(profile=getattr(session, "profile", None) or None)
    except Exception:
        return None


def _open_session_authority(session):
    """Open the Agent's authoritative SessionDB for *session*, or ``None``.

    Contributor rework for PR #7075 review item #2: every durable transcript
    mutation in this module goes through this handle
    (``SessionDB.rewind_to_message`` / ``SessionDB.replace_messages``) — the
    Agent's transaction authority owns cut validation, the active-set CAS, the
    live-turn-lease / compression guards and the message counters, instead of
    the WebUI hand-rolling its own ``SELECT``/``UPDATE`` path around them.
    Callers must ``close()`` the handle.
    """
    try:
        from hermes_state import SessionDB
    except Exception:
        return None
    db_path = _session_state_db_path(session)
    if not db_path:
        return None
    try:
        return SessionDB(db_path)
    except Exception:
        logger.warning(
            "checkpoint: state.db authority unavailable for %s",
            getattr(session, "session_id", "?"),
            exc_info=True,
        )
        return None


def _durable_rows_exist(session) -> bool:
    """Cheap read-only probe: does state.db hold ANY row for this session?

    Decides whether the delete path needs a durable rewrite at all. It
    deliberately does NOT open the write-capable SessionDB for sessions with
    no durable rows (a pre-persistence session keeps its historic sidecar-only
    behavior rather than us faking a durable write against an empty store).
    """
    sid = getattr(session, "session_id", None)
    if not sid:
        return False
    db_path = _session_state_db_path(session)
    if not db_path or not os.path.exists(str(db_path)):
        return False
    try:
        import sqlite3
        conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True, timeout=5.0)
        try:
            row = conn.execute(
                "SELECT 1 FROM messages WHERE session_id = ? LIMIT 1", (str(sid),)
            ).fetchone()
            return row is not None
        finally:
            conn.close()
    except Exception:
        return False


def _durable_active_id_set(session_id: str):
    """Ids of currently-active durable rows (reader semantics), or ``None``."""
    rows = _read_active_state_db_rows(session_id)
    if rows is None:
        return None
    return {int(r["id"]) for r in rows}


def _display_stamp_int(message):
    """Durable id stamped on a display row (``_row_id`` family), or ``None``."""
    if not isinstance(message, dict):
        return None
    for key in ("_row_id", "_db_persisted_row_id", "row_id"):
        raw = message.get(key)
        if raw is None:
            continue
        try:
            value = int(raw)
        except (TypeError, ValueError):
            continue
        if value > 0:
            return value
    return None


def _strip_row_stamps(rows) -> None:
    """Drop durable-id stamps a durable rewrite has invalidated.

    ``replace_messages(archive_dropped=True)`` archives the divergent suffix
    and re-inserts it with NEW ids; the old stamps on the corresponding
    display rows would point at archived rows. Clearing them makes the next
    load/merge re-derive the fresh identities from the durable transcript
    instead of trusting stale ids.
    """
    for row in rows or []:
        if isinstance(row, dict):
            for key in ("_row_id", "_db_persisted_row_id", "row_id"):
                row.pop(key, None)


def _busy_exceptions() -> tuple:
    """The Agent's transcript-contention exception classes (empty if absent)."""
    try:
        from hermes_state import SessionCompressionInProgressError
        from hermes_state_errors import (
            CompressionSessionClosedError,
            SessionTurnLeaseLostError,
        )
        return (
            SessionCompressionInProgressError,
            CompressionSessionClosedError,
            SessionTurnLeaseLostError,
        )
    except Exception:
        return ()


def _raise_mapped_authority_error(exc: BaseException) -> None:
    """Map the Agent transaction's errors onto the WebUI error taxonomy.

    Never returns: translates to CheckpointBusyError / CheckpointStaleError,
    or re-raises the original exception.
    """
    busy = _busy_exceptions()
    if busy and isinstance(exc, busy):
        if type(exc).__name__ == "SessionTurnLeaseLostError":
            raise CheckpointBusyError(
                "Session has an active turn; wait for it to finish before retrying."
            ) from exc
        raise CheckpointBusyError(
            "Session history is locked by compression (or is closed by it); "
            "retry once compression finishes."
        ) from exc
    if isinstance(exc, RuntimeError):
        # rewind_to_message / replace_messages raise RuntimeError for the
        # in-txn CAS rejections ("active transcript changed ..." / "rewind
        # target changed ..."): the caller's view is stale, not the request.
        raise CheckpointStaleError(
            "The transcript changed since this view was rendered; "
            "reload the session and retry."
        ) from exc
    raise exc


def _commit_rewind_via_authority(session, session_id: str, cut_row_id: int):
    """Soft-archive the durable suffix through ``SessionDB.rewind_to_message``.

    Mirrors ``SessionDB.rewind_user_turn``'s CAS protocol (the ONE rewind
    implementation behind the CLI, the gateway and the TUI):
      * the canonical live payload of the target row pins the message
        (presentation-only metadata changes do not invalidate it),
      * an ordered snapshot of the active ids pins the active set,
      * the write re-validates both INSIDE its transaction, enforces the
        live-turn-lease and compression guards there, and updates the
        message counters and ``rewind_count``.

    Returns ``(archived_ids, survivor_ids)``. The archived set is derived from
    the CAS-verified snapshot: every active row with ``id >= cut`` — exactly
    the rows the transaction soft-archived (the same inclusive-cut contract as
    the gateway's truncate-before path). Raises CheckpointBusyError /
    CheckpointStaleError / ValueError; RuntimeError when the durable authority
    itself is unavailable.
    """
    db = _open_session_authority(session)
    if db is None:
        raise RuntimeError(
            "state.db authority unavailable; refusing to archive the durable transcript"
        )
    try:
        try:
            stored = db.get_messages_as_conversation(session_id, include_row_ids=True)
        except Exception as exc:
            raise RuntimeError(f"could not read the durable transcript: {exc}") from exc
        from agent.context_compressor import user_originated_turn_view
        target_row = None
        for message in stored:
            if message.get("_row_id") == cut_row_id:
                target_row = message
                break
        if target_row is None:
            raise CheckpointStaleError(
                "The selected message is not in the durable transcript; "
                "reload the session and retry."
            )
        stored_view = user_originated_turn_view(target_row)
        if stored_view is None:
            # Present but not a user-originated turn: a bad target (400-class),
            # not a stale view.
            raise ValueError(
                f"restore target must be a user-originated turn (row {int(cut_row_id)})"
            )
        try:
            expected_active_ids = [int(i) for i in db.get_active_message_ids(session_id)]
        except Exception as exc:
            raise RuntimeError(f"could not snapshot the durable active set: {exc}") from exc
        try:
            db.rewind_to_message(
                session_id,
                int(cut_row_id),
                expected_active_ids=expected_active_ids,
                expected_target_content=stored_view.get("content"),
            )
        except Exception as exc:  # noqa: BLE001 - mapped below, never swallowed
            _raise_mapped_authority_error(exc)
            raise
        archived = [i for i in expected_active_ids if i >= int(cut_row_id)]
        survivors = [i for i in expected_active_ids if i < int(cut_row_id)]
        committed_ids = _durable_active_id_set(session_id)
        if committed_ids is not None and not set(survivors) <= committed_ids:
            # Post-commit verification: a survivor row must still be active.
            # (A concurrently appended row is fine — ids grow above the cut.)
            raise RuntimeError(
                "durable transcript did not retain its survivor prefix; refusing to publish"
            )
        return archived, survivors
    finally:
        try:
            db.close()
        except Exception:
            pass


def _delete_display_drop_plan(session, message_id: str, scope: str):
    """Display-side drop plan: ``(drop_ids, target_idx)`` for a delete.

    Extracted so the durable planner and the sidecar splice share ONE
    definition of what the delete targets (drift between the two would delete
    different rows in the two stores).
    """
    if scope not in ("single", "pair"):
        raise ValueError(f"scope must be 'single' or 'pair', got {scope!r}")
    history = list(session.messages or [])
    target_idx = None
    for i, row in enumerate(history):
        if isinstance(row, dict) and row.get('id') == message_id:
            target_idx = i
            break
    if target_idx is None:
        raise ValueError(f"message_id {message_id!r} not found in session")
    drop_ids: set[str] = {message_id}
    if scope == "pair":
        role = history[target_idx].get('role')
        if role == 'user':
            sibling = history[target_idx + 1] if target_idx + 1 < len(history) else None
            if isinstance(sibling, dict) and sibling.get('role') == 'assistant':
                sibling_id = sibling.get('id')
                if sibling_id:
                    drop_ids.add(sibling_id)
        elif role == 'assistant':
            sibling = history[target_idx - 1] if target_idx - 1 >= 0 else None
            if isinstance(sibling, dict) and sibling.get('role') == 'user':
                sibling_id = sibling.get('id')
                if sibling_id:
                    drop_ids.add(sibling_id)
        # For tool/system/tombstone rows or missing siblings, pair collapses to single.
    return drop_ids, target_idx


def _norm_head(value, limit: int = 400) -> str:
    """Normalized head of a message's text for lenient identity matching."""
    if isinstance(value, list):
        value = " ".join(
            part.get("text") or "" for part in value
            if isinstance(part, dict) and part.get("type") == "text"
        )
    if not isinstance(value, str) or not value:
        return ""
    import re as _re
    head = value[:600].replace("\r\n", "\n").replace("\r", "\n")
    return _re.sub(r"\s+", " ", head).strip()[:limit]


def _lenient_row_match(display_row, durable_row) -> bool:
    """Role + normalized-content identity between display and durable rows."""
    if not isinstance(display_row, dict) or not isinstance(durable_row, dict):
        return False
    if str(display_row.get('role') or '') != str(durable_row.get('role') or ''):
        return False
    a, b = _norm_head(display_row.get('content')), _norm_head(durable_row.get('content'))
    if not a or not b:
        return not a and not b
    return a == b


def _plan_durable_delete(session, session_id: str, message_id: str, scope: str) -> dict:
    """Resolve the durable rows a per-message delete must remove.

    Attribution order (fail-closed; refusing beats deleting wrong rows):
      1. a still-valid ``_row_id`` stamp on the target display row,
      2. the content-anchored display→durable walk shared with the restore
         resolver (``api/checkpoint_map.build_restore_plan``; a user turn's
         ``exact`` cut IS its durable row),
      3. positional mapping of the assistant bubble inside its turn stretch
         (i-th assistant display row ↔ i-th assistant durable row between the
         same two user rows) plus the assistant's contiguous tool run — and
         the same for a pair-sibling.
    Returns ``{"drop_row_ids": [...], "target_row_id": int|None}``. Raises
    CheckpointStaleError when the target (or its pair sibling) cannot be
    attributed to the durable transcript.
    """
    db = _open_session_authority(session)
    if db is None:
        raise RuntimeError("state.db authority unavailable; refusing the durable delete")
    try:
        stored = db.get_messages_as_conversation(session_id, include_row_ids=True)
    finally:
        try:
            db.close()
        except Exception:
            pass
    rows = [m for m in stored if isinstance(m, dict)]
    ordered_ids = [m.get("_row_id") for m in rows if isinstance(m.get("_row_id"), int)]
    by_id = {
        m.get("_row_id"): m for m in rows if isinstance(m.get("_row_id"), int)
    }
    history = [m for m in (session.messages or []) if isinstance(m, dict)]

    from api.checkpoint_map import build_restore_plan
    plan = build_restore_plan(session, history) or {}

    def _stamp_valid(idx):
        if not (0 <= idx < len(history)):
            return None
        rid = _display_stamp_int(history[idx])
        if rid is None or rid not in by_id:
            return None
        return rid if _lenient_row_match(history[idx], by_id[rid]) else None

    def _user_row_id(display_idx):
        if display_idx is None:
            return None
        entry = plan.get(display_idx) or {}
        if entry.get('cut_row_id') is not None and entry.get('mode') == 'exact':
            return int(entry['cut_row_id'])
        return _stamp_valid(display_idx)

    def _prev_user_idx(display_idx):
        for j in range(display_idx - 1, -1, -1):
            if history[j].get('role') == 'user':
                return j
        return None

    def _next_user_idx(display_idx):
        for j in range(display_idx + 1, len(history)):
            if history[j].get('role') == 'user':
                return j
        return None

    def _assistant_run(row_id):
        """[assistant row_id] + the contiguous tool rows that answer it."""
        if row_id not in ordered_ids:
            return []
        pos = ordered_ids.index(row_id)
        run = [row_id]
        for rid in ordered_ids[pos + 1:]:
            if by_id[rid].get('role') == 'tool':
                run.append(rid)
            else:
                break
        return run

    def _assistant_run_for(display_idx):
        """Durable run ids for an assistant display row, or None (stale)."""
        stamped = _stamp_valid(display_idx)
        if stamped is not None and by_id[stamped].get('role') == 'assistant':
            return _assistant_run(stamped)
        prev_u, next_u = _prev_user_idx(display_idx), _next_user_idx(display_idx)
        lo = _user_row_id(prev_u) if prev_u is not None else None
        if prev_u is not None and lo is None:
            return None
        hi = _user_row_id(next_u) if next_u is not None else None
        if next_u is not None and hi is None:
            return None
        durable_run_heads = [
            rid for rid in ordered_ids
            if by_id[rid].get('role') == 'assistant'
            and (lo is None or rid > lo) and (hi is None or rid < hi)
        ]
        display_rows = [
            j for j in range(len(history))
            if history[j].get('role') == 'assistant'
            and (prev_u is None or j > prev_u) and (next_u is None or j < next_u)
        ]
        if len(display_rows) != len(durable_run_heads):
            return None
        try:
            k = display_rows.index(display_idx)
        except ValueError:
            return None
        return _assistant_run(durable_run_heads[k])

    drop_ids, target_idx = _delete_display_drop_plan(session, message_id, scope)
    target_display = history[target_idx]
    role = str(target_display.get('role') or '')
    drop_row_ids: list[int] = []
    target_row_id = None
    if role == 'user':
        target_row_id = _user_row_id(target_idx)
        if target_row_id is None:
            raise CheckpointStaleError(
                "Could not attribute this message to the durable transcript; "
                "reload the session and retry."
            )
        drop_row_ids.append(target_row_id)
        if scope == 'pair':
            sibling_idx = target_idx + 1 if (
                target_idx + 1 < len(history)
                and history[target_idx + 1].get('role') == 'assistant'
            ) else None
            if sibling_idx is not None:
                run = _assistant_run_for(sibling_idx)
                if run is None:
                    raise CheckpointStaleError(
                        "Could not attribute the paired reply to the durable "
                        "transcript; reload the session and retry."
                    )
                drop_row_ids.extend(run)
    elif role == 'assistant':
        run = _assistant_run_for(target_idx)
        if run is None:
            raise CheckpointStaleError(
                "Could not attribute this reply to the durable transcript; "
                "reload the session and retry."
            )
        target_row_id = run[0]
        drop_row_ids.extend(run)
        if scope == 'pair':
            sibling_idx = target_idx - 1 if (
                target_idx - 1 >= 0 and history[target_idx - 1].get('role') == 'user'
            ) else None
            if sibling_idx is not None:
                sibling_row_id = _user_row_id(sibling_idx)
                if sibling_row_id is None:
                    raise CheckpointStaleError(
                        "Could not attribute the paired prompt to the durable "
                        "transcript; reload the session and retry."
                    )
                drop_row_ids.insert(0, sibling_row_id)
    else:
        stamped = _stamp_valid(target_idx)
        if stamped is None:
            raise CheckpointStaleError(
                "Could not attribute this message to the durable transcript; "
                "reload the session and retry."
            )
        target_row_id = stamped
        drop_row_ids.append(stamped)
    seen: set[int] = set()
    drop_row_ids = [rid for rid in drop_row_ids if not (rid in seen or seen.add(rid))]
    return {"drop_row_ids": drop_row_ids, "target_row_id": target_row_id}


def _commit_durable_delete(session, session_id: str, drop_row_ids: list[int]) -> dict:
    """Remove the resolved rows from the durable transcript atomically.

    Uses ``SessionDB.replace_messages(archive_dropped=True)`` — the
    rewind/edit/regenerate primitive: dropped rows are SOFT-archived
    (``active=0``, recoverable) rather than DELETE'd, the in-order kept prefix
    keeps its ids, and the divergent suffix is archived + re-inserted.
    ``reject_active_turn_lease=True`` runs the in-transaction live-turn guard;
    the same call enforces the compression guards and updates the counters.
    """
    db = _open_session_authority(session)
    if db is None:
        raise RuntimeError("state.db authority unavailable; refusing the durable delete")
    try:
        try:
            stored = db.get_messages_as_conversation(session_id, include_row_ids=True)
        except Exception as exc:
            raise RuntimeError(f"could not read the durable transcript: {exc}") from exc
        drop = {int(x) for x in drop_row_ids}
        kept = [
            m for m in stored
            if not (isinstance(m.get("_row_id"), int) and m["_row_id"] in drop)
        ]
        if len(kept) == len(stored):
            raise CheckpointStaleError(
                "The durable rows for this message are already gone; "
                "reload the session and retry."
            )
        try:
            db.replace_messages(
                session_id, kept, archive_dropped=True, reject_active_turn_lease=True
            )
        except Exception as exc:  # noqa: BLE001 - mapped below, never swallowed
            _raise_mapped_authority_error(exc)
            raise
        return {"dropped": sorted(drop), "kept_count": len(kept)}
    finally:
        try:
            db.close()
        except Exception:
            pass


def _publish_session_sidecar(session, session_id: str, *, marker_kind: str, marker_fields: dict) -> None:
    """Persist the mutated sidecar after a durable commit; fail CLOSED.

    The sidecar was rebuilt from the COMMITTED durable result, so a failed
    save must not be reported as success: retry once, then flag the session
    (``needs_state_resync``) and write the crash-safe resync marker
    (``api/durable_sync``) whose correction every later load re-applies —
    stale on-disk sidecar data can never resurrect the removed suffix. Raises
    RuntimeError when the publish persistently fails.
    """
    last_exc: Exception | None = None
    for attempt in (1, 2):
        try:
            session.save()
            try:
                session.needs_state_resync = False
            except Exception:
                pass
            return
        except Exception as exc:  # noqa: BLE001 - retried once, then surfaced
            last_exc = exc
            logger.warning(
                "checkpoint: sidecar publish attempt %d failed for %s: %s",
                attempt, session_id, exc,
            )
    try:
        session.needs_state_resync = True
    except Exception:
        pass
    try:
        from api import durable_sync
        durable_sync.write_resync_marker(
            session_id, kind=marker_kind, **marker_fields
        )
    except Exception:
        logger.error(
            "checkpoint: could not write resync marker for %s", session_id, exc_info=True
        )
    raise RuntimeError(
        "The durable transcript was updated but the WebUI transcript could not "
        "be saved; the session is flagged for resync — reload before continuing."
    ) from last_exc


def _fail_closed_after_durable_commit(session, session_id, *, marker_kind, marker_fields, message):
    """Flag + mark + raise for post-commit local failures (verification etc.)."""
    try:
        session.needs_state_resync = True
    except Exception:
        pass
    try:
        from api import durable_sync
        durable_sync.write_resync_marker(session_id, kind=marker_kind, **marker_fields)
    except Exception:
        logger.error(
            "checkpoint: resync marker write failed for %s", session_id, exc_info=True
        )
    raise RuntimeError(message)


def _commit_and_publish_restore(session, session_id: str, *, keep: int, cut_row_id, mode: str) -> dict[str, Any]:
    """Commit a checkpoint restore and publish the sidecar from the result.

    Order (the dual-store contract from the PR #7075 review):
      1. DURABLE FIRST — the inclusive-cut soft archive goes through the Agent
         transaction authority (:func:`_commit_rewind_via_authority`); any
         refusal (bad target, CAS, live turn, compression) aborts with the
         sidecar untouched.
      2. PUBLISH FROM THE COMMITTED RESULT — the sidecar is truncated to the
         display prefix and re-validated against the committed survivor id
         set; a mismatch between the committed state and the display view is
         itself fail-closed (flag + marker + raise), and the persist itself
         goes through :func:`_publish_session_sidecar` (retry, then flag +
         marker + raise).

    Returns the restore-result dict shared by both entry points.
    """
    archived_ids: list[int] = []
    survivor_ids: list[int] = []
    if cut_row_id is not None:
        archived_ids, survivor_ids = _commit_rewind_via_authority(
            session, session_id, int(cut_row_id)
        )
    marker_fields = {
        "keep_index": int(keep),
        "survivor_row_ids": [int(x) for x in survivor_ids],
        "archived_row_ids": [int(x) for x in archived_ids],
        "durable_cut_row_id": int(cut_row_id) if cut_row_id is not None else None,
        "profile": getattr(session, "profile", None),
    }
    with LOCK:
        s = SESSIONS.get(session_id, session)
        history = list(s.messages or [])
        if keep > len(history):
            _fail_closed_after_durable_commit(
                s, session_id, marker_kind="restore", marker_fields=marker_fields,
                message="session transcript changed during checkpoint archive; retry",
            )
        survivor_messages = history[:keep]
        if cut_row_id is not None:
            committed_ids = _durable_active_id_set(session_id)
            committed = committed_ids if committed_ids is not None else set(survivor_ids)
            for row in survivor_messages:
                stamp = _display_stamp_int(row)
                if stamp is not None and stamp not in committed:
                    _fail_closed_after_durable_commit(
                        s, session_id, marker_kind="restore", marker_fields=marker_fields,
                        message=(
                            "the displayed transcript diverged from the committed "
                            "durable state; reload before restoring"
                        ),
                    )
        old_count = len(history)
        s.messages = survivor_messages
        _stamp_intentional_shrink_generation(s, old_count, len(s.messages))
        s.truncation_watermark = _truncation_watermark_for(s.messages)
        s.truncation_boundary = s.truncation_watermark
        ctx = getattr(s, 'context_messages', None)
        if isinstance(ctx, list) and ctx:
            aligned_ctx = truncate_context_for_display_keep(ctx, history, keep)
            if aligned_ctx is not None:
                s.context_messages = aligned_ctx
        marker_fields["watermark"] = s.truncation_watermark
        marker_fields["boundary"] = s.truncation_boundary
    _publish_session_sidecar(
        s, session_id, marker_kind="restore", marker_fields=marker_fields
    )
    survivor_row_ids = [_display_stamp_int(m) for m in (s.messages or [])]
    logger.info(
        "checkpoint_restore %s: mode=%s cut_row=%s, messages %d->%d, archived_state_rows=%d",
        session_id, mode, cut_row_id, old_count, len(s.messages), len(archived_ids),
    )
    return {
        'restored_to_row_id': cut_row_id,
        'restore_mode': mode,
        'archive_mode': 'archive' if archived_ids else 'display-only',
        'old_message_count': old_count,
        'new_message_count': len(s.messages),
        'archived_state_row_ids': archived_ids,
        'survivor_user_row_ids': survivor_row_ids,
        'survivor_row_id_map': {
            str(rid): rid for rid in survivor_row_ids if rid is not None
        },
    }


def _sidecar_row_matches_durable(sidecar_row: dict, durable_row: dict) -> bool:
    """Content/role identity check between a sidecar row and its state.db twin.

    Guards against a stale or wrong-role durable anchor: the checkpoint the
    client pointed at must be the same *message* in both stores before we cut.
    Role must match exactly; for plain-text content the sanitized text must
    match, otherwise (multimodal/None) role-only match is accepted.
    """
    if not isinstance(sidecar_row, dict) or not isinstance(durable_row, dict):
        return False
    if sidecar_row.get('role') != durable_row.get('role'):
        return False
    sc = sidecar_row.get('content')
    dc = durable_row.get('content')
    if isinstance(sc, str) and isinstance(dc, str):
        # Compare leading 4KB after light normalization; identical prompt text.
        a = sc.strip()[:4096]
        b = dc.strip()[:4096]
        return a == b
    return True


def restore_checkpoint_at_row_id(session_id: str, target_row_id: int) -> dict[str, Any]:
    """Restore the conversation to the durable state BEFORE the given user row.

    Parity with Hermes Desktop's "Restore checkpoint" feature
    (apps/desktop/src/app/session/hooks/use-prompt-actions/index.ts#restoreToMessage).
    The address is a durable ``row_id`` (state.db primary key) stamped on the
    sidecar row as ``m._row_id``. There is deliberately **no** sidecar-ordinal
    fallback: an older sidecar that never stamped a durable id simply cannot be
    checkpointed, and the UI hides the control for those rows. The gateway
    refuses ordinal-only truncation as unsafe for durable history (see
    tui_gateway _resolve_truncate_row_id); we mirror that fail-closed contract.

    Correctness / integrity rules:
      * read-only and live-turn sessions are refused **before any write**.
      * the anchor row must be an ACTIVE durable user row whose content matches
        the sidecar row (guards stale / wrong-role / cross-session ids).
      * state.db soft-archive (``active=0``) is committed FIRST through the
        Agent's transaction authority (SessionDB.rewind_to_message: in-txn
        target + active-set CAS validation, live-turn/compression guards,
        message counters); the WebUI sidecar is written ONLY from the committed
        survivor transcript. Any durable-write failure aborts the whole
        restore (no partial success).
      * the archived suffix is computed from the state.db ordinal, so tool /
        reasoning / compaction rows diverging from the sidecar cannot make this
        archive the wrong durable rows.

    Raises:
        KeyError: session not found
        PermissionError: read-only session
        ValueError: bad id type, unknown / inactive / wrong-role / non-user row,
                    or content mismatch
        CheckpointBusyError: a live turn / compression owns the transcript
        CheckpointStaleError: the durable transcript changed under the view
        RuntimeError: durable write failed (restore aborted, sidecar untouched)
    """
    if isinstance(target_row_id, bool) or not isinstance(target_row_id, int):
        raise ValueError("row_id must be an integer")
    if target_row_id <= 0:
        raise ValueError("row_id must be a positive durable row identifier")

    with _get_session_agent_lock(session_id):
        s = get_session(session_id)  # raises KeyError
        with LOCK:
            s = SESSIONS.get(session_id, s)  # stale-object guard
            # Ownership / mutability gates BEFORE any mutation.
            if getattr(s, "read_only", False):
                raise PermissionError(f"Session {session_id} is read-only")
            # Reject while a turn is live (open stream or pending user message).
            if _live_active_stream_id(s) or getattr(s, "pending_user_message", None):
                raise ValueError(
                    "Session has an active turn; wait for it to finish before restoring."
                )
            history = s.messages or []
            if not history:
                raise ValueError("Session has no messages to restore.")

            # Locate the anchor by durable id in the SIDE CAR (for the cut point).
            target_idx = None
            for i, m in enumerate(history):
                if not isinstance(m, dict):
                    continue
                rid = (m.get('_row_id') or m.get('_db_persisted_row_id') or m.get('row_id'))
                if rid is None:
                    continue
                try:
                    if int(rid) == target_row_id:
                        target_idx = i
                        break
                except (TypeError, ValueError):
                    continue
            if target_idx is None:
                raise ValueError(
                    f"row_id {target_row_id} not found in the session transcript; "
                    "refusing to truncate to a guessed index"
                )

            target_message = history[target_idx]
            if target_message.get('role') != 'user':
                raise ValueError(
                    f"row_id {target_row_id} is a {target_message.get('role')!r} row, "
                    "not a user message; only user turns can be used as checkpoints"
                )

            # Cross-check against the durable authority: the same durable id must
            # exist, be active, be a user row, and match the sidecar content.
            durable_anchor = _state_db_active_row_by_id(session_id, target_row_id)
            if durable_anchor is None:
                raise ValueError(
                    f"row_id {target_row_id} is not an active durable row in state.db; "
                    "the checkpoint is stale or belongs to a different session"
                )
            if durable_anchor.get('role') != 'user':
                raise ValueError(
                    f"row_id {target_row_id} resolves to a {durable_anchor.get('role')!r} "
                    "durable row, not a user message"
                )
            if not _sidecar_row_matches_durable(target_message, durable_anchor):
                raise ValueError(
                    f"row_id {target_row_id} content does not match the durable row; "
                    "refusing to cut on a mismatched checkpoint"
                )

            keep = target_idx

        # --- DURABLE COMMIT + FAIL-CLOSED PUBLICATION -----------------------
        # The durable soft archive goes through the Agent's transaction
        # authority (SessionDB.rewind_to_message: in-txn target/CAS validation
        # + live-turn/compression guards) and the sidecar is published
        # strictly from its committed result — see _commit_and_publish_restore.
        return _commit_and_publish_restore(
            s, session_id, keep=keep, cut_row_id=target_row_id, mode="durable-row-id",
        )


def restore_checkpoint_to_display_message(
    session_id: str,
    *,
    message_id: Any = None,
    msg_idx: Any = None,
    message_ts: Any = None,
    row_id: Any = None,
) -> dict[str, Any]:
    """Restore the conversation to the checkpoint BEFORE a displayed user turn.

    Display-addressed companion to :func:`restore_checkpoint_at_row_id`:
    instead of requiring a stamped durable ``row_id`` on the sidecar row, the
    target is resolved server-side by ``api/checkpoint_map`` (content-anchored,
    monotonic, fail-closed) so legacy rows without a stamp — and rows whose
    stamp went stale after a history rewrite — can still be restored.

    Resolution modes: ``exact`` / ``anchor`` / ``anchor-next`` archive the
    durable suffix from the resolved cut row through the Agent's transaction
    authority; ``display-only`` archives nothing (no durable row is
    attributable to the target or later) and only truncates the sidecar +
    model context. The durable archive is committed FIRST; any failure aborts
    before the sidecar is touched (dual-store fail-closed), and a sidecar
    publish failure after the commit is fail-closed via the resync marker
    (``api/durable_sync.py``).

    Raises:
        KeyError: session not found
        PermissionError: read-only session
        ValueError: bad/missing target address, stale view, unresolvable
                    message
        CheckpointBusyError: a live turn / compression owns the transcript
        CheckpointStaleError: the durable transcript changed under the view
        RuntimeError: durable write failed (restore aborted, sidecar untouched)
    """
    if row_id is not None and (isinstance(row_id, bool) or not isinstance(row_id, int)):
        raise ValueError("row_id must be an integer")
    if msg_idx is not None and (isinstance(msg_idx, bool) or not isinstance(msg_idx, int)):
        raise ValueError("msg_idx must be an integer")
    if message_id is not None and isinstance(message_id, bool):
        raise ValueError("message_id must be a string or integer")
    if message_id is None and msg_idx is None and row_id is None:
        raise ValueError("message_id, msg_idx or row_id is required")

    with _get_session_agent_lock(session_id):
        s = get_session(session_id)  # raises KeyError
        with LOCK:
            s = SESSIONS.get(session_id, s)  # stale-object guard
            # Ownership / mutability gates BEFORE any mutation.
            if getattr(s, "read_only", False):
                raise PermissionError(f"Session {session_id} is read-only")
            # Reject while a turn is live (open stream or pending user message).
            if _live_active_stream_id(s) or getattr(s, "pending_user_message", None):
                raise ValueError(
                    "Session has an active turn; wait for it to finish before restoring."
                )
            history = s.messages or []
            if not history:
                raise ValueError("Session has no messages to restore.")

            # --- locate the target DISPLAY row (stable sidecar id first) -------
            target_idx = None
            if message_id is not None:
                for i, m in enumerate(history):
                    if not isinstance(m, dict):
                        continue
                    mid = m.get('id')
                    if mid is None:
                        continue
                    if str(mid) == str(message_id):
                        target_idx = i
                        break
                if target_idx is not None and history[target_idx].get('role') != 'user':
                    raise ValueError("Only user messages can be used as checkpoints")
            if target_idx is None and msg_idx is not None:
                if msg_idx < 0 or msg_idx >= len(history):
                    raise ValueError(
                        "The selected message is no longer in the transcript; "
                        "reload the session and retry"
                    )
                candidate = history[msg_idx]
                if not isinstance(candidate, dict) or candidate.get('role') != 'user':
                    raise ValueError("Only user messages can be used as checkpoints")
                # Staleness check: the ordinal alone is only trustworthy when
                # the timestamp the client saw still matches that row.
                if message_ts is not None:
                    try:
                        want_ts = float(message_ts)
                    except (TypeError, ValueError):
                        want_ts = None
                    if want_ts is not None:
                        try:
                            got_ts = float(candidate.get('timestamp'))
                        except (TypeError, ValueError):
                            got_ts = None
                        if got_ts is not None and abs(got_ts - want_ts) > 5.0:
                            raise ValueError(
                                "The transcript changed since this view was rendered; "
                                "reload the session and retry"
                            )
                target_idx = msg_idx
            if target_idx is None:
                raise ValueError(
                    "Could not locate the selected message in the current transcript; "
                    "reload the session and retry"
                )
            target_message = history[target_idx]

            # --- resolve the durable cut ---------------------------------------
            from api.checkpoint_map import build_restore_plan
            plan = build_restore_plan(s, history).get(target_idx)
            cut_row_id = None
            mode = None
            if plan:
                cut_row_id = plan.get('cut_row_id')
                mode = plan.get('mode')
            if plan is None and row_id is not None and row_id > 0:
                # Stamp-only fallback (the resolver had no durable view): the
                # row's own stamp must still point at an active,
                # content-matching durable user row — the same checks as
                # restore_checkpoint_at_row_id.
                stamp = (target_message.get('_row_id')
                         or target_message.get('_db_persisted_row_id')
                         or target_message.get('row_id'))
                try:
                    stamp = int(stamp) if stamp is not None else None
                except (TypeError, ValueError):
                    stamp = None
                if stamp == row_id:
                    anchor = _state_db_active_row_by_id(session_id, row_id)
                    if anchor is None:
                        raise ValueError(
                            f"row_id {row_id} is not an active durable row in state.db; "
                            "the checkpoint is stale or belongs to a different session"
                        )
                    if anchor.get('role') != 'user':
                        raise ValueError(
                            f"row_id {row_id} resolves to a {anchor.get('role')!r} durable row, "
                            "not a user message"
                        )
                    if not _sidecar_row_matches_durable(target_message, anchor):
                        raise ValueError(
                            f"row_id {row_id} content does not match the durable row; "
                            "refusing to cut on a mismatched checkpoint"
                        )
                    cut_row_id = row_id
                    mode = 'legacy-stamp'

            keep = target_idx

        # --- DURABLE COMMIT + FAIL-CLOSED PUBLICATION -----------------------
        # The durable soft archive goes through the Agent's transaction
        # authority (SessionDB.rewind_to_message: in-txn target/CAS validation
        # + live-turn/compression guards) and the sidecar is published
        # strictly from its committed result — see _commit_and_publish_restore.
        return _commit_and_publish_restore(
            s, session_id, keep=keep, cut_row_id=cut_row_id, mode=mode,
        )


def undo_last(session_id: str) -> dict[str, Any]:
    """Remove the most recent user message and everything after it.

    Mirrors gateway/run.py:_handle_undo_command. Returns a preview of the
    removed text so the UI can confirm to the user.

    Raises:
        KeyError: session not found
        ValueError: no user message in transcript
    """
    # Acquire the per-session agent lock as the outermost lock so that the
    # read-modify-write of s.messages is serialised with the periodic
    # checkpoint thread, cancel_stream, and all other session writers.
    # Lock ordering: _agent_lock → LOCK → _write_session_index (LOCK).
    with _get_session_agent_lock(session_id):
        s = get_session(session_id)  # acquires LOCK transiently
        with LOCK:
            # Stale-object guard — see retry_last for the rationale.
            s = SESSIONS.get(session_id, s)
            history = s.messages or []
            last_user_idx = None
            for i in range(len(history) - 1, -1, -1):
                if history[i].get('role') == 'user':
                    last_user_idx = i
                    break
            if last_user_idx is None:
                raise ValueError('Nothing to undo.')

            removed_text = _extract_text(history[last_user_idx].get('content', ''))
            removed_count = len(history) - last_user_idx
            s.messages = history[:last_user_idx]
            _stamp_intentional_shrink_generation(s, len(history), len(s.messages))
            s.truncation_watermark = _truncation_watermark_for(s.messages)
            # Persist the original truncate cutoff.
            s.truncation_boundary = s.truncation_watermark
            if isinstance(getattr(s, 'context_messages', None), list) and s.context_messages:
                truncated_context = _truncate_at_last_user(s.context_messages)
                if truncated_context is not None:
                    s.context_messages = truncated_context
        s.save()  # outside LOCK -- save() re-acquires LOCK via _write_session_index()
    preview = (removed_text[:40] + '...') if len(removed_text) > 40 else removed_text
    return {
        'removed_count': removed_count,
        'removed_preview': preview,
    }


def session_status(session_id: str) -> dict[str, Any]:
    """Return a snapshot of session state for /status.

    Webui equivalent of gateway/run.py:_handle_status_command. The agent's
    "agent_running" comes from `session_key in self._running_agents`; the
    webui equivalent is whether the session has an active stream
    (active_stream_id is set).
    """
    s = get_session(session_id)
    inp = int(s.input_tokens or 0)
    out = int(s.output_tokens or 0)
    profile = getattr(s, 'profile', None) or 'default'
    try:
        from api.profiles import get_hermes_home_for_profile
        hermes_home = str(get_hermes_home_for_profile(profile))
    except Exception:
        hermes_home = ''
    return {
        'session_id': s.session_id,
        'title': s.title,
        'model': s.model,
        'profile': profile,
        'hermes_home': hermes_home,
        'workspace': s.workspace,
        'personality': s.personality,
        'message_count': len(s.messages or []),
        'created_at': s.created_at,
        'updated_at': s.updated_at,
        'agent_running': bool(getattr(s, 'active_stream_id', None)),
        # Expose the stream id itself (not just the agent_running bool) so a
        # hidden-tab poller can attach the live renderer to a server-initiated
        # turn (self-wake / cron / restart hook) without opening the persistent
        # per-session SSE while the tab is hidden. See messages.js hidden-tab
        # active-stream poll. Additive field — existing consumers ignore it.
        #
        # CRITICAL: only expose a stream id that is actually LIVE in this
        # process. After a restart/crash the persisted active_stream_id is stale
        # (the in-memory STREAMS/ACTIVE_RUNS were wiped) — handing that dead id
        # to the poller would make it attach a renderer to a stream that never
        # produces tokens (a permanent fake "thinking" state). Mirror
        # _clear_stale_stream_state's liveness test: a stream counts as live
        # only if it's in STREAMS (SSE channel open) or ACTIVE_RUNS (worker
        # bookkeeping). Otherwise report None so the poller waits for a REAL
        # server_turn_started instead of latching a ghost.
        'active_stream_id': _live_active_stream_id(s),
        'input_tokens': inp,
        'output_tokens': out,
        'total_tokens': inp + out,
        'estimated_cost': s.estimated_cost,
    }


def session_usage(session_id: str) -> dict[str, Any]:
    """Return token usage and cost for /usage.

    Mirrors gateway/run.py:_handle_usage_command's basic counters. The
    agent shows additional fields (rate-limit headroom etc.) that depend
    on provider API responses we don't have in webui -- those are deferred.
    """
    s = get_session(session_id)
    inp = int(s.input_tokens or 0)
    out = int(s.output_tokens or 0)
    return {
        'input_tokens': inp,
        'output_tokens': out,
        'total_tokens': inp + out,
        'estimated_cost': s.estimated_cost,
        'model': s.model,
    }


def _extract_text(content: Any) -> str:
    """Flatten message content to plain text. Agent stores either a string
    or a list of {type, text|...} parts; webui needs the user-typed text."""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for p in content:
            if isinstance(p, dict) and p.get('type') == 'text':
                parts.append(p.get('text', ''))
        return ' '.join(parts)
    return str(content)
